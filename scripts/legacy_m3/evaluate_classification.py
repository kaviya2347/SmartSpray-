"""
FILE PATH: SmartSpray/scripts/evaluate_classification.py

PURPOSE:
    Evaluates the REAL trained Module 3 disease-classification model
    (models/classification/best.keras) on actual evaluation images.

    IMPORTANT — dataset integrity finding:
        The repository does NOT contain a dedicated held-out test set.
        The training notebook's own 500-image "test" split was built with
        Keras validation_split=0.1 on the same prepared_dataset directory,
        and (as verified by scripts/analyze_splits.py) those 500 images are
        a strict subset of the 1002-image validation split used during model
        selection. That means the notebook's reported 98.4% "test accuracy"
        is NOT a genuine held-out test accuracy.

        Therefore this script evaluates the model on:
          1. The 1002-image validation split  (labelled Validation-set performance,
             the most appropriate evaluation data available).
          2. The notebook's 500-image sub-split (labelled Notebook 500-image split,
             provided for comparison with the training notebook, with the
             caveat that it overlaps the validation split).

        Ground-truth labels always come from the class sub-folder names in
        models/classification/prepared_dataset/ — never from predictions.

    Preprocessing matches the training notebook EXACTLY:
        - ImageDataGenerator(preprocessing_function=preprocess_input,
                             validation_split=0.2, seed=42)
        - flow_from_directory(target_size=(224,224), batch_size=32,
                              class_mode="categorical", subset="validation",
                              shuffle=False)
        - Keras assigns class indices alphabetically, which matches
          class_order.json => 0=early_blight, 1=healthy, 2=late_blight,
          3=septoria_leaf_spot.

    USAGE:
        python scripts/evaluate_classification.py

    OUTPUTS (saved to models/classification/evaluation/):
        - evaluation_metrics.json     summary metrics (accuracy, macro/weighted)
        - classification_report.csv   per-class precision/recall/f1/support
        - confusion_matrix.png        confusion matrix heatmap
        - misclassified.csv           per-misclassification detail (if any)
        - evaluation_summary.txt      human readable summary

DEPENDENCIES:
    - tensorflow (keras) for model loading + ImageDataGenerator
    - numpy, pandas, matplotlib, seaborn, sklearn
"""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import seaborn as sns  # noqa: E402
from sklearn.metrics import (  # noqa: E402
    accuracy_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from tensorflow.keras.applications.efficientnet import preprocess_input  # noqa: E402
from tensorflow.keras.preprocessing.image import ImageDataGenerator  # noqa: E402

# ── Paths ──────────────────────────────────────────────────────────────────────
REPO_ROOT = Path(__file__).resolve().parent.parent
MODEL_PATH = REPO_ROOT / "models" / "classification" / "best.keras"
PREPARED_DIR = REPO_ROOT / "models" / "classification" / "prepared_dataset"
CLASS_ORDER_PATH = REPO_ROOT / "models" / "classification" / "class_order.json"
OUTPUT_DIR = REPO_ROOT / "models" / "classification" / "evaluation"

# ── Config (must match the training notebook) ────────────────────────────────
IMAGE_SIZE = 224
BATCH_SIZE = 32
RANDOM_SEED = 42
VALIDATION_SPLIT = 0.2
NOTEBOOK_TEST_SPLIT = 0.1


def load_class_order() -> list[str]:
    """Load the class order exactly as the production classifier does."""
    with open(CLASS_ORDER_PATH, "r") as f:
        data = json.load(f)
    return list(data["class_order"])


def build_validation_generator(validation_split: float):
    """Recreate a Keras generator identical to the training notebook's config."""
    datagen = ImageDataGenerator(
        preprocessing_function=preprocess_input,
        validation_split=validation_split,
    )
    gen = datagen.flow_from_directory(
        PREPARED_DIR,
        target_size=(IMAGE_SIZE, IMAGE_SIZE),
        batch_size=BATCH_SIZE,
        class_mode="categorical",
        subset="validation",
        seed=RANDOM_SEED,
        shuffle=False,
    )
    return gen


def evaluate_model(model, generator, class_order: list[str]) -> dict:
    """
    Run the REAL model over a Keras generator and compute full metrics.

    Never touches test_classification.py, never uses mocked predictions,
    never invents ground-truth labels (generator.classes comes from folder
    structure generated by Keras flow_from_directory).
    """
    filepaths = [str(p) for p in generator.filepaths]
    y_true = list(generator.classes)

    # Predict in one pass over the generator (shuffle=False => order matches
    # generator.classes exactly, so predictions align with ground-truth labels).
    raw_preds = model.predict(generator, verbose=1)

    n = len(filepaths)
    y_pred_idxs = [int(np.argmax(row)) for row in raw_preds]
    confidences = [float(np.max(row)) for row in raw_preds]
    prob_rows = [[float(v) for v in row] for row in raw_preds]

    # ── Sanity checks ──────────────────────────────────────────────────────────
    assert len(y_pred_idxs) == n, "prediction count != sample count"
    assert len(y_true) == n, "label count != sample count"
    assert set(y_true) <= set(range(len(class_order))), "invalid true label"
    assert set(y_pred_idxs) <= set(range(len(class_order))), "invalid prediction"

    # ── Metrics ────────────────────────────────────────────────────────────────
    y_true_arr = np.array(y_true)
    y_pred_arr = np.array(y_pred_idxs)

    accuracy = accuracy_score(y_true_arr, y_pred_arr)
    precision_macro = precision_score(y_true_arr, y_pred_arr, average="macro")
    recall_macro = recall_score(y_true_arr, y_pred_arr, average="macro")
    f1_macro = f1_score(y_true_arr, y_pred_arr, average="macro")
    precision_weighted = precision_score(y_true_arr, y_pred_arr, average="weighted")
    recall_weighted = recall_score(y_true_arr, y_pred_arr, average="weighted")
    f1_weighted = f1_score(y_true_arr, y_pred_arr, average="weighted")

    per_class_precision = precision_score(y_true_arr, y_pred_arr, average=None)
    per_class_recall = recall_score(y_true_arr, y_pred_arr, average=None)
    per_class_f1 = f1_score(y_true_arr, y_pred_arr, average=None)

    cm = confusion_matrix(y_true_arr, y_pred_arr)

    # ── Confidence statistics ──────────────────────────────────────────────────
    conf_arr = np.array(confidences)
    correct_mask = y_true_arr == y_pred_arr

    results: dict = {
        "n_samples": int(n),
        "accuracy": float(accuracy),
        "accuracy_percent": float(accuracy * 100),
        "macro_precision": float(precision_macro),
        "macro_recall": float(recall_macro),
        "macro_f1": float(f1_macro),
        "weighted_precision": float(precision_weighted),
        "weighted_recall": float(recall_weighted),
        "weighted_f1": float(f1_weighted),
        "confidence_mean": float(conf_arr.mean()),
        "confidence_median": float(np.median(conf_arr)),
        "confidence_min": float(conf_arr.min()),
        "confidence_max": float(conf_arr.max()),
        "confidence_mean_correct": float(conf_arr[correct_mask].mean())
        if correct_mask.any()
        else None,
        "confidence_mean_incorrect": float(conf_arr[~correct_mask].mean())
        if (~correct_mask).any()
        else None,
        "n_correct": int(correct_mask.sum()),
        "n_incorrect": int((~correct_mask).sum()),
        "per_class": {
            class_order[i]: {
                "true_support": int((y_true_arr == i).sum()),
                "predicted_support": int((y_pred_arr == i).sum()),
                "precision": float(per_class_precision[i]),
                "recall": float(per_class_recall[i]),
                "f1": float(per_class_f1[i]),
            }
            for i in range(len(class_order))
        },
        "confusion_matrix": cm.tolist(),
        "class_order": class_order,
        "misclassified": [],
    }

    # ── Error analysis ─────────────────────────────────────────────────────────
    mis = []
    for idx in np.where(~correct_mask)[0]:
        mis.append(
            {
                "filename": Path(filepaths[idx]).name,
                "actual_class": class_order[y_true_arr[idx]],
                "predicted_class": class_order[y_pred_arr[idx]],
                "confidence": confidences[idx],
                "probabilities": {
                    class_order[i]: prob_rows[idx][i]
                    for i in range(len(class_order))
                },
            }
        )
    results["misclassified"] = mis

    return results


def plot_confusion_matrix(
    cm: np.ndarray,
    class_order: list[str],
    title: str,
    save_path: Path,
) -> None:
    """Render and save a confusion matrix heatmap."""
    fig, ax = plt.subplots(figsize=(8, 6))
    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        xticklabels=class_order,
        yticklabels=class_order,
        cmap="Blues",
        ax=ax,
    )
    ax.set_title(title)
    ax.set_ylabel("True Label")
    ax.set_xlabel("Predicted Label")
    plt.xticks(rotation=30, ha="right")
    plt.tight_layout()
    fig.savefig(save_path, dpi=150)
    plt.close(fig)


def write_results(
    results: dict,
    class_order: list[str],
    prefix: str,
    title: str,
) -> None:
    """Persist metrics JSON, classification report CSV, and confusion image."""
    # ── metrics JSON (without the bulky misclassified list) ───────────────────
    metrics_json = {
        k: v for k, v in results.items() if k != "misclassified"
    }
    metrics_path = OUTPUT_DIR / f"{prefix}_metrics.json"
    metrics_path.write_text(json.dumps(metrics_json, indent=2), encoding="utf-8")

    # ── classification report CSV ─────────────────────────────────────────────
    rows = []
    for cls in class_order:
        pc = results["per_class"][cls]
        rows.append(
            {
                "class": cls,
                "precision": pc["precision"],
                "recall": pc["recall"],
                "f1": pc["f1"],
                "support": pc["true_support"],
            }
        )
    df = pd.DataFrame(rows)
    report_path = OUTPUT_DIR / f"{prefix}_classification_report.csv"
    df.to_csv(report_path, index=False)

    # ── confusion matrix image ────────────────────────────────────────────────
    cm_path = OUTPUT_DIR / f"{prefix}_confusion_matrix.png"
    plot_confusion_matrix(
        np.array(results["confusion_matrix"]),
        class_order,
        title,
        cm_path,
    )

    # ── misclassified CSV ─────────────────────────────────────────────────────
    mis_path = OUTPUT_DIR / f"{prefix}_misclassified.csv"
    if results["misclassified"]:
        pd.DataFrame(results["misclassified"]).to_csv(mis_path, index=False)
    else:
        pd.DataFrame(
            columns=["filename", "actual_class", "predicted_class",
                     "confidence", "probabilities"]
        ).to_csv(mis_path, index=False)

    print(f"  -> {metrics_path}")
    print(f"  -> {report_path}")
    print(f"  -> {cm_path}")
    print(f"  -> {mis_path}")
def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    class_order = load_class_order()
    print(f"Class order from class_order.json: {class_order}")
    assert len(class_order) == 4, "Expected exactly 4 classes"
    assert class_order == [
        "early_blight",
        "healthy",
        "late_blight",
        "septoria_leaf_spot",
    ], "class_order.json does not match the canonical disease names"

    import tensorflow as tf

    model = tf.keras.models.load_model(str(MODEL_PATH))
    print(f"Model loaded: {MODEL_PATH}")
    print(f"Input shape : {model.inputs[0].shape}")
    print(f"Output shape: {model.outputs[0].shape}")
    assert model.outputs[0].shape[-1] == len(class_order), (
        "model output dim != number of classes"
    )
    assert tuple(model.inputs[0].shape[1:]) == (224, 224, 3), (
        "unexpected model input shape (expected 224x224x3)"
    )

    summary_lines: list[str] = []

    def record(msg: str) -> None:
        print(msg)
        summary_lines.append(msg)

    # ── Evaluation 1: validation split (1002 images) ──────────────────────────
    record("=" * 70)
    record("EVALUATION 1 — VALIDATION SPLIT (20% of prepared dataset)")
    record("=" * 70)
    val_gen = build_validation_generator(VALIDATION_SPLIT)
    record(f"Validation images found: {val_gen.samples}")
    record(f"Per-class validation counts:")
    for cls, idx in sorted(
        val_gen.class_indices.items(), key=lambda kv: kv[1]
    ):
        record(
            f"  {cls}: {(val_gen.classes == idx).sum()}"
        )
    val_results = evaluate_model(model, val_gen, class_order)
    record(
        f"Validation accuracy: {val_results['accuracy']:.4f} "
        f"({val_results['accuracy_percent']:.2f}%)"
    )
    record(
        f"Macro   P/R/F1: "
        f"{val_results['macro_precision']:.4f} / "
        f"{val_results['macro_recall']:.4f} / "
        f"{val_results['macro_f1']:.4f}"
    )
    record(
        f"Weighted P/R/F1: "
        f"{val_results['weighted_precision']:.4f} / "
        f"{val_results['weighted_recall']:.4f} / "
        f"{val_results['weighted_f1']:.4f}"
    )

    write_results(
        val_results,
        class_order,
        prefix="validation",
        title="Confusion Matrix — Validation Split",
    )

    # ── Evaluation 2: notebook's 500-image subset ─────────────────────────────
    record("")
    record("=" * 70)
    record("EVALUATION 2 — NOTEBOOK 500-IMAGE SPLIT (for comparison only)")
    record("=" * 70)
    record("CAVEAT: this 500-image split is a strict subset of the validation")
    record("split (verified by scripts/analyze_splits.py) — NOT a held-out test.")
    nb_gen = build_validation_generator(NOTEBOOK_TEST_SPLIT)
    record(f"Notebook split images found: {nb_gen.samples}")
    nb_results = evaluate_model(model, nb_gen, class_order)
    record(
        f"Notebook-split accuracy: {nb_results['accuracy']:.4f} "
        f"({nb_results['accuracy_percent']:.2f}%)"
    )

    write_results(
        nb_results,
        class_order,
        prefix="notebook_split",
        title="Confusion Matrix — Notebook 500-Image Split",
    )

    # ── Write combined summary ─────────────────────────────────────────────────
    summary_text = "\n".join(summary_lines)
    summary_path = OUTPUT_DIR / "evaluation_summary.txt"
    summary_path.write_text(summary_text, encoding="utf-8")
    print(f"\nSummary written to: {summary_path}")


if __name__ == "__main__":
    main()